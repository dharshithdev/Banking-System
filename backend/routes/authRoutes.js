const express = require('express');
const router = express.Router();
const controller = require('../controllers/authController');
const { authenticate } = require('../middleware/auth');
const { login: validateLogin, verifyOtp, resendOtp } = require('../middleware/validate');
const rateLimit = require('../middleware/rateLimit');
const authRateLimiter = rateLimit({ windowMs: 15 * 60 * 1000, max: 10 });
const resendRateLimiter = rateLimit({ windowMs: 15 * 60 * 1000, max: 3 });
router.post('/login', validateLogin, controller.login);
router.post('/verify-otp', authRateLimiter, verifyOtp, controller.verifyOtp);
router.post('/resend-otp', resendRateLimiter, resendOtp, controller.resendOtp);
router.post('/logout', authenticate, controller.logout);
router.get('/me', authenticate, controller.me);
module.exports = router;
